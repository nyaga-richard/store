-- Backoffice / purchasing extensions.
-- Applied AFTER db/schema.sql, which remains the exact 21-table specification.
-- Every statement is safe to re-run on every deploy.

ALTER TABLE product ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true;
CREATE INDEX IF NOT EXISTS idx_product_is_active ON product (is_active);

CREATE TABLE IF NOT EXISTS staff_user (
  staff_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(255) UNIQUE NOT NULL,
  password_hash varchar(255) NOT NULL,
  first_name varchar(100) NOT NULL,
  last_name varchar(100) NOT NULL,
  role varchar(30) NOT NULL DEFAULT 'staff',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamp NOT NULL,
  CONSTRAINT ck_staff_role CHECK (role IN ('owner', 'admin', 'manager', 'staff'))
);

CREATE TABLE IF NOT EXISTS supplier (
  supplier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_name varchar(150) UNIQUE NOT NULL,
  contact_name varchar(100),
  email varchar(255),
  phone varchar(30),
  address_line1 varchar(255),
  city varchar(100),
  created_at timestamp NOT NULL
);

CREATE TABLE IF NOT EXISTS purchase_order (
  purchase_order_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id int NOT NULL,
  order_number varchar(50) UNIQUE NOT NULL,
  order_date timestamp NOT NULL,
  expected_date timestamp,
  status varchar(30) NOT NULL DEFAULT 'Draft',
  subtotal decimal(12,2) NOT NULL DEFAULT 0,
  notes text,
  created_at timestamp NOT NULL,
  updated_at timestamp NOT NULL,
  CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES supplier (supplier_id),
  CONSTRAINT ck_po_status CHECK (status IN ('Draft', 'Ordered', 'Received', 'Cancelled'))
);

CREATE TABLE IF NOT EXISTS purchase_order_line (
  purchase_order_line_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id int NOT NULL,
  variant_id int NOT NULL,
  quantity int NOT NULL,
  unit_cost decimal(10,2) NOT NULL,
  received_quantity int NOT NULL DEFAULT 0,
  CONSTRAINT fk_pol_order FOREIGN KEY (purchase_order_id) REFERENCES purchase_order (purchase_order_id),
  CONSTRAINT fk_pol_variant FOREIGN KEY (variant_id) REFERENCES product_variant (variant_id),
  CONSTRAINT ck_pol_quantity CHECK (quantity > 0),
  CONSTRAINT ck_pol_cost CHECK (unit_cost >= 0),
  CONSTRAINT ck_pol_received CHECK (received_quantity >= 0),
  CONSTRAINT uq_pol_order_variant UNIQUE (purchase_order_id, variant_id)
);

-- Editable storefront settings, used by the header, footer and home page.
CREATE TABLE IF NOT EXISTS site_setting (
  setting_key varchar(100) PRIMARY KEY,
  setting_value text NOT NULL,
  updated_at timestamp NOT NULL
);

-- Gateway credentials are editable in /admin/payments. Secret values never go to the browser.
CREATE TABLE IF NOT EXISTS payment_gateway_setting (
  setting_key varchar(100) PRIMARY KEY,
  setting_value text NOT NULL,
  updated_at timestamp NOT NULL
);
